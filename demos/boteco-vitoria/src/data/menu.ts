export function itemMatchesCategory(item: MenuItem, category: MenuCategory) {
  if (category === "todos") return true;
  return item.category === category || item.extraCategories?.includes(category);
}

export function itemMatchesQuery(item: MenuItem, query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return true;
  return (
    item.name.toLowerCase().includes(q) ||
    item.description.toLowerCase().includes(q) ||
    item.tags?.some((tag) => tag.toLowerCase().includes(q)) ||
    item.price.toLowerCase().includes(q)
  );
}

export function portionLabel(portion?: Portion) {
  if (portion === "P1") return "Serve 1";
  if (portion === "P2") return "Serve 2";
  if (portion === "P4") return "Serve 4";
  return undefined;
}
